// Deploys Vibentry to Cloudflare Workers through the Cloudflare API. No wrangler, no npm dependencies.
//   CLOUDFLARE_API_TOKEN=… node scripts/deploy-cloudflare.mjs [--dry-run]
// Optional: CLOUDFLARE_ACCOUNT_ID (needed only if the token sees several accounts), WORKER_NAME (default "vibentry").
// What it uploads: the worker modules reachable from server/worker.mjs, a content module built in memory from data/
// (never written to disk; it lives only inside the deployed script and is not served), and public/ embedded as data modules
// (served by the worker itself; fits the free plan's 3 MB script limit and needs no separate asset upload).
// It sets APP_URL and NODE_ENV only. BOT_TOKEN (secret), ADMIN_IDS and the other settings are managed in the Cloudflare
// dashboard (Worker → Settings → Variables and Secrets) and are kept across deploys. Nothing secret is printed.
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MIME } from '../server/http-common.mjs';
import { loadContent } from '../server/content-node.mjs';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const dryRun = process.argv.includes('--dry-run');
const name = process.env.WORKER_NAME || 'vibentry';
const API = 'https://api.cloudflare.com/client/v4';
const CLASS = 'VibentryApp';
const COMPATIBILITY_DATE = '2025-10-01'; // >= 2025-04-01: process.env is filled from the worker's variables

async function cf(pathname, { method = 'GET', body, token = process.env.CLOUDFLARE_API_TOKEN } = {}) {
  const response = await fetch(API + pathname, { method, headers: { Authorization: `Bearer ${token}`, ...(body && !(body instanceof FormData) ? { 'Content-Type': 'application/json' } : {}) }, body: body instanceof FormData ? body : body ? JSON.stringify(body) : undefined });
  const data = await response.json().catch(() => ({}));
  if (!response.ok || data.success === false) throw new Error(`Cloudflare ${method} ${pathname.replace(/accounts\/[0-9a-f]+/, 'accounts/…')}: ${response.status} ${(data.errors || []).map(e => `${e.code} ${e.message}`).join('; ')}`);
  return data.result;
}
// Worker modules: follow relative imports from the entry so Node-only files (node:sqlite, fs) are never uploaded.
async function moduleGraph(entry) {
  const seen = new Map(); const queue = [entry];
  while (queue.length) {
    const file = queue.shift(); if (seen.has(file)) continue;
    const code = await readFile(path.join(root, file), 'utf8'); seen.set(file, code);
    for (const [, spec] of code.matchAll(/(?:^|\n)\s*(?:import|export)\s[^'"]*?from\s+'(\.{1,2}\/[^']+)'/g)) {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(file), spec));
      if (!['server/content-bundle.mjs', 'server/public-bundle.mjs'].includes(target)) queue.push(target);
    }
  }
  return seen;
}
async function publicFiles(dir = 'public') {
  const files = [];
  for (const entry of await readdir(path.join(root, dir), { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) files.push(...await publicFiles(rel));
    else if (MIME[path.extname(entry.name)]) files.push(rel);
  }
  return files;
}

const modules = await moduleGraph('server/worker.mjs');
const content = await loadContent();
const bundle = `// Generated by scripts/deploy-cloudflare.mjs at deploy time. Private course content: do not commit.\nexport default ${JSON.stringify(content)};\n`;
const assets = await Promise.all((await publicFiles()).map(async file => ({ file, key: '/' + file.slice('public/'.length), data: await readFile(path.join(root, file)), type: MIME[path.extname(file)] })));
const textType = type => /^text\/|json|svg/.test(type);
const publicBundle = `// Generated by scripts/deploy-cloudflare.mjs at deploy time.\n${assets.map((a, i) => `import f${i} from '../${a.file}';`).join('\n')}\nexport default {\n${assets.map((a, i) => `  ${JSON.stringify(a.key)}: { body: f${i}, type: ${JSON.stringify(a.type)} },`).join('\n')}\n};\n`;
const paid = content.lessons.length >= 24;
console.log(`Worker "${name}": ${modules.size} modules, content: ${content.lessons.length} lessons, ${content.prompts.items?.length || 0} prompts, ${content.articles.length} articles${paid ? '' : ' (private data/ missing: demo content only)'}; ${assets.length} public files.`);
if (dryRun) { console.log([...modules.keys()].join('\n')); console.log(assets.map(a => a.key).join('\n')); process.exit(0); }
if (!process.env.CLOUDFLARE_API_TOKEN) { console.error('Set CLOUDFLARE_API_TOKEN (Workers Scripts: Edit). Do not paste it into chats.'); process.exit(1); }

let account = process.env.CLOUDFLARE_ACCOUNT_ID;
if (!account) { const list = await cf('/accounts'); if (list.length !== 1) { console.error('Several accounts: set CLOUDFLARE_ACCOUNT_ID.'); process.exit(1); } account = list[0].id; }
const base = `/accounts/${account}/workers`;
const subdomain = (await cf(`${base}/subdomain`)).subdomain;
const appUrl = `https://${name}.${subdomain}.workers.dev`;
const existing = (await cf(`${base}/scripts`)).find(s => s.id === name);

// 1. The script. The Durable Object class gets SQLite storage on the first deploy (migration v1).
const metadata = {
  main_module: 'server/worker.mjs', compatibility_date: COMPATIBILITY_DATE, compatibility_flags: ['nodejs_compat'],
  bindings: [{ type: 'durable_object_namespace', name: 'APP', class_name: CLASS }, { type: 'plain_text', name: 'APP_URL', text: appUrl }, { type: 'plain_text', name: 'NODE_ENV', text: 'production' }],
  keep_bindings: ['plain_text', 'secret_text'],
  ...(existing?.migration_tag ? {} : { migrations: { new_tag: 'v1', new_sqlite_classes: [CLASS] } }),
};
const form = new FormData();
form.append('metadata', new Blob([JSON.stringify(metadata)], { type: 'application/json' }));
for (const [file, code] of modules) form.append(file, new File([code], file, { type: 'application/javascript+module' }));
form.append('server/content-bundle.mjs', new File([bundle], 'server/content-bundle.mjs', { type: 'application/javascript+module' }));
form.append('server/public-bundle.mjs', new File([publicBundle], 'server/public-bundle.mjs', { type: 'application/javascript+module' }));
for (const a of assets) form.append(a.file, new File([a.data], a.file, { type: textType(a.type) ? 'text/plain' : 'application/octet-stream' }));
await cf(`${base}/scripts/${name}`, { method: 'PUT', body: form });
// 2. Public address on workers.dev.
await cf(`${base}/scripts/${name}/subdomain`, { method: 'POST', body: { enabled: true, previews_enabled: false } });
console.log(`Deployed: ${appUrl}\nCheck: ${appUrl}/health`);
